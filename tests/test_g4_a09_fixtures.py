"""Task a09 checks: deterministic synthetic fixtures and declared expectations.

Every fixture is regenerated from committed code and compared against the hash
recorded in research/g4/a09/fixture-registry.json. The historical G2 reference
is additionally compared against the hash quoted in the G2 evidence record and,
when present, byte for byte against the committed artifact.

No native APIs, no iTunes, no COM, no UI. Generated bytes are written only to
pytest temporary directories, never into the repository.
"""

from __future__ import annotations

import copy
import hashlib
import importlib.util
import json
import struct
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
A09_DIR = REPO_ROOT / "research" / "g4" / "a09"
REGISTRY_PATH = A09_DIR / "fixture-registry.json"
EXPECTATIONS_DIR = A09_DIR / "expectations"


def _load_module(module_name, path):
    spec = importlib.util.spec_from_file_location(module_name, path)
    module = importlib.util.module_from_spec(spec)
    # dataclasses resolve their owning module through sys.modules, so register
    # before executing or @dataclass fails under postponed annotations.
    sys.modules[module_name] = module
    spec.loader.exec_module(module)
    return module


fixtures = _load_module("a09_fixtures", A09_DIR / "fixtures.py")
manifests = _load_module("a09_manifest", A09_DIR / "manifest.py")

REGISTRY = json.loads(REGISTRY_PATH.read_text(encoding="utf-8"))
ROWS = {row["fixture_id"]: row for row in REGISTRY["fixtures"]}
ALL_IDS = [row["fixture_id"] for row in REGISTRY["fixtures"]]
SILENCE_ID = "ITL-G4-A09-PCM-48000-MONO-0010-SILENCE"
ODD_ID = "ITL-G4-A09-PCM-48000-MONO-1500-INFO-ODD"


