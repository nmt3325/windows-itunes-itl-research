def test_registry_is_current_for_this_generator():
    assert REGISTRY["schema"] == fixtures.REGISTRY_SCHEMA
    assert REGISTRY["generator"] == fixtures.GENERATOR_PATH
    current = fixtures.sha256_file(A09_DIR / "fixtures.py")
    assert REGISTRY["generator_sha256"] == current, (
        "fixture-registry.json is stale, regenerate it with "
        "python3 research/g4/a09/fixtures.py --write-registry research/g4/a09/fixture-registry.json"
    )
    assert sorted(ALL_IDS) == sorted(spec.fixture_id for spec in fixtures.SPECS)


def test_reference_regeneration_matches_quoted_record():
    quoted = fixtures.REFERENCE_QUOTED
    data = fixtures.build_fixture(fixtures.spec_by_id(fixtures.REFERENCE_ID))
    assert len(data) == quoted["bytes"]
    assert hashlib.sha256(data).hexdigest() == quoted["sha256"]
    assert hashlib.sha256(fixtures.data_payload(data)).hexdigest() == quoted["pcm_sha256"]


def test_reference_regeneration_is_byte_identical_to_committed_artifact():
    artifact = REPO_ROOT / fixtures.REFERENCE_ARTIFACT
    if not artifact.exists():
        pytest.skip("reference artifact is not present in this checkout")
    data = fixtures.build_fixture(fixtures.spec_by_id(fixtures.REFERENCE_ID))
    assert artifact.read_bytes() == data


