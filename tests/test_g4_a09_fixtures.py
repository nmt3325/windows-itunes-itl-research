@pytest.mark.parametrize("fixture_id", ALL_IDS)
def test_riff_structure_matches_declared_layout(fixture_id):
    row = ROWS[fixture_id]
    spec = fixtures.spec_by_id(fixture_id)
    data = fixtures.build_fixture(spec)
    chunks = fixtures.chunk_map(data)
    assert chunks == row["chunks"]
    ids = [chunk["id"] for chunk in chunks]
    assert ids[0] == "fmt "
    assert ids.count("data") == 1
    fmt_chunk = chunks[0]
    audio_format, channels, rate, byte_rate, block_align, bits = struct.unpack_from(
        "<HHIIHH", data, fmt_chunk["payload_offset"]
    )
    assert audio_format == 1
    assert channels == spec.channels == row["channels"]
    assert rate == spec.sample_rate_hz == row["sample_rate_hz"]
    assert bits == spec.bits_per_sample == row["bits_per_sample"]
    assert block_align == channels * bits // 8
    assert byte_rate == rate * block_align
    payload = fixtures.data_payload(data)
    assert len(payload) == spec.frames * block_align
    data_chunk = [chunk for chunk in chunks if chunk["id"] == "data"][0]
    if spec.metadata_shape == "none":
        assert ids == ["fmt ", "data"]
        assert data_chunk["payload_offset"] == 44, "canonical 44 byte header expected"
    if spec.metadata_placement == "before_data":
        assert data_chunk["payload_offset"] != 44, "metadata before data must shift the audio"


@pytest.mark.parametrize("fixture_id", ALL_IDS)
def test_samples_stay_in_range_and_match_recorded_stats(fixture_id):
    row = ROWS[fixture_id]
    data = fixtures.build_fixture(fixtures.spec_by_id(fixture_id))
    payload = fixtures.data_payload(data)
    values = struct.unpack("<%dh" % (len(payload) // 2), payload)
    assert min(values) >= -32768
    assert max(values) <= 32767
    assert fixtures.pcm_stats(payload) == row["pcm"]


def test_family_covers_the_declared_variation_matrix():
    rates = {row["sample_rate_hz"] for row in REGISTRY["fixtures"]}
    channels = {row["channels"] for row in REGISTRY["fixtures"]}
    durations = {row["duration_ms"] for row in REGISTRY["fixtures"]}
    shapes = {row["metadata_shape"] for row in REGISTRY["fixtures"]}
    assert {8000, 22050, 44100, 48000} <= rates
    assert {1, 2} <= channels
    assert len(durations) >= 4
    assert {"none", "riff-info-ascii", "riff-info-odd", "id3v23-unicode"} <= shapes
    assert ROWS[SILENCE_ID]["pcm"]["peak_abs"] == 0
    assert all(row["pcm"]["peak_abs"] <= 32767 for row in REGISTRY["fixtures"])


def test_family_exercises_riff_pad_bytes():
    subchunk_pads = 0
    for fixture_id in ALL_IDS:
        data = fixtures.build_fixture(fixtures.spec_by_id(fixture_id))
        for chunk in fixtures.chunk_map(data):
            subchunk_pads += sum(sub["pad_bytes"] for sub in chunk.get("subchunks", []))
    assert subchunk_pads >= 1, "no fixture exercises RIFF pad bytes"
    odd_lists = [chunk for chunk in ROWS[ODD_ID]["chunks"] if chunk["id"] == "LIST"]
    assert odd_lists, "the odd length fixture must carry a LIST chunk"
    assert any(sub["pad_bytes"] == 1 for sub in odd_lists[0]["subchunks"])


def test_stereo_channels_are_distinguishable():
    spec = fixtures.spec_by_id("ITL-G4-A09-PCM-48000-STEREO-1500")
    payload = fixtures.data_payload(fixtures.build_fixture(spec))
    values = struct.unpack("<%dh" % (len(payload) // 2), payload)
    left = values[0::2]
    right = values[1::2]
    assert len(left) == len(right) == spec.frames
    assert left != right, "a stereo fixture whose channels match cannot show channel order"


