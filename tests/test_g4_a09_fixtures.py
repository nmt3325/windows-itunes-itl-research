def test_written_fixture_carries_the_declared_mtime(tmp_path):
    spec = fixtures.spec_by_id(SILENCE_ID)
    path = fixtures.write_fixture(tmp_path, spec, fixtures.build_fixture(spec))
    assert path.stat().st_mtime_ns == spec.mtime_ns
    assert hashlib.sha256(path.read_bytes()).hexdigest() == ROWS[SILENCE_ID]["sha256"]


def test_generator_refuses_to_materialise_inside_the_repository():
    spec = fixtures.spec_by_id(SILENCE_ID)
    with pytest.raises(SystemExit):
        fixtures.write_fixture(A09_DIR / "unwanted-binaries", spec, b"")
    assert not (A09_DIR / "unwanted-binaries").exists()


