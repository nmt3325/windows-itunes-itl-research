def _complete_declaration(kind="native_import_discovery", fixture_ids=None):
    chosen = list(fixture_ids) if fixture_ids else ALL_IDS[:3]
    manifest = manifests.build_template(
        REGISTRY,
        candidate_id="A09-SELFTEST-0001",
        candidate_kind=kind,
        fixture_ids=chosen,
        playlist_name="A09 Self Test Order",
    )
    manifest["declaration_state"] = "declared"
    manifest["preflight"] = {
        "a08_review_id": "a08-review-selftest",
        "a11_review_id": "a11-review-selftest",
        "coordinator_slot": "selftest-slot",
    }
    library = manifest["library"]
    library["intended_library_path"] = "synthetic/a09-selftest/iTunes Library.itl"
    library["input"] = {"sha256": "0" * 64, "size_bytes": 4096, "mtime_ns": 1789084800000000000}
    if kind == "independent_writer_acceptance":
        library["expected_output"] = {"sha256": "1" * 64, "size_bytes": 8192}
    else:
        library["expected_output"] = {
            "sha256": None,
            "size_bytes": None,
            "unpredictable_reason": "native assigns identifiers and internal ordering keys",
            "capture_required": True,
        }
    for entry in manifest["media_inputs"]:
        entry["declared_location"] = "synthetic/a09-selftest/media/" + entry["filename"]
        entry["expected_native_title_source"] = (
            "filename" if entry["metadata_shape"] == "none" else "embedded tag"
        )
    for index, entry in enumerate(manifest["identities"]["entries"]):
        entry["old"] = {
            "present": False,
            "value": None,
            "absent_reason": "fresh synthetic library, no prior row",
        }
        if kind == "independent_writer_acceptance":
            entry["new"] = {"assignment": "declared", "value": "A09DECLARED%04d" % index}
    for phase in ("before", "after"):
        for row in manifest["locations"][phase]:
            row["path"] = "synthetic/a09-selftest/media/" + ROWS[row["fixture_id"]]["filename"]
    for playlist in manifest["playlists"]:
        playlist["order"] = list(reversed(playlist["membership"]))
        if kind == "independent_writer_acceptance":
            playlist["persistent_id"] = {"assignment": "declared", "value": "A09PLAYLIST0001"}
    return manifest


@pytest.mark.parametrize(
    "name", ["candidate-native-import-discovery.json", "candidate-independent-writer-acceptance.json"]
)
def test_committed_templates_are_structurally_valid_but_not_runnable(name):
    manifest = json.loads((EXPECTATIONS_DIR / name).read_text(encoding="utf-8"))
    assert manifest["schema"] == manifests.EXPECTATION_SCHEMA
    assert manifest["declaration_state"] == "template"
    assert manifest["operator"] == "a10"
    assert manifests.validate(manifest, registry=REGISTRY) == []
    runnable, problems = manifests.is_runnable(manifest, registry=REGISTRY)
    assert not runnable
    assert any("not declared" in problem for problem in problems)
    alignment = manifest["format_alignment"]
    assert alignment["format_owner"] == "a08"
    assert alignment["a08_format_published_at_authoring_time"] is False


@pytest.mark.parametrize("kind", list(manifests.CANDIDATE_KINDS))
def test_complete_declaration_is_runnable(kind):
    manifest = _complete_declaration(kind)
    runnable, problems = manifests.is_runnable(manifest, registry=REGISTRY)
    assert problems == []
    assert runnable


def _drop_identity(manifest):
    manifest["identities"]["entries"].pop()


def _clear_location(manifest):
    manifest["media_inputs"][0]["declared_location"] = None


def _forge_media_hash(manifest):
    manifest["media_inputs"][0]["sha256"] = "f" * 64


def _allow_protected_change(manifest):
    manifest["permitted_native_changes"]["allowed"].append("media_file_bytes")


def _drop_protected_field(manifest):
    manifest["permitted_native_changes"]["must_not_change"].remove("playlist_order")


def _prefill_observation(manifest):
    manifest["observations"]["library_output_sha256"] = "2" * 64


def _break_playlist_order(manifest):
    manifest["playlists"][0]["order"] = manifest["playlists"][0]["order"][:-1]


def _weaken_acceptance(manifest):
    manifest["acceptance"]["restart_cycles"] = 1
    manifest["acceptance"]["damaged_file_fallback_allowed"] = True


def _wrong_operator(manifest):
    manifest["operator"] = "a09"


def _drop_preflight(manifest):
    manifest["preflight"]["a08_review_id"] = None


def _predeclare_discovery_output(manifest):
    manifest["library"]["expected_output"]["sha256"] = "3" * 64


@pytest.mark.parametrize(
    "mutate,needle",
    [
        (_drop_identity, "identities is missing"),
        (_clear_location, "declared_location is required"),
        (_forge_media_hash, "the registry records"),
        (_allow_protected_change, "both allowed and protected"),
        (_drop_protected_field, "must_not_change is missing"),
        (_prefill_observation, "must stay empty until the run is executed"),
        (_break_playlist_order, "permutation of membership"),
        (_weaken_acceptance, "restart_cycles must be at least 2"),
        (_wrong_operator, "operator must be a10"),
        (_drop_preflight, "preflight.a08_review_id is required"),
        (_predeclare_discovery_output, "must not predeclare an output hash"),
    ],
)
def test_incomplete_declarations_are_rejected(mutate, needle):
    manifest = _complete_declaration()
    mutate(manifest)
    runnable, problems = manifests.is_runnable(manifest, registry=REGISTRY)
    assert not runnable
    assert any(needle in problem for problem in problems), problems


def test_writer_acceptance_must_declare_every_new_identifier():
    manifest = _complete_declaration("independent_writer_acceptance")
    entry = manifest["identities"]["entries"][0]
    entry["new"] = {
        "assignment": "native_assigned_to_observe",
        "value": None,
        "observation_slot": "observations.observed_identities",
    }
    runnable, problems = manifests.is_runnable(manifest, registry=REGISTRY)
    assert not runnable
    assert any("must declare every new id" in problem for problem in problems), problems


def test_writer_acceptance_must_predeclare_the_output_hash():
    manifest = _complete_declaration("independent_writer_acceptance")
    manifest["library"]["expected_output"] = {"sha256": None, "size_bytes": None}
    runnable, problems = manifests.is_runnable(manifest, registry=REGISTRY)
    assert not runnable
    assert any("predeclare library.expected_output.sha256" in problem for problem in problems), problems


def test_declared_media_must_match_the_reproducible_registry():
    manifest = _complete_declaration()
    original = copy.deepcopy(manifest)
    manifest["media_inputs"][0]["frames"] = original["media_inputs"][0]["frames"] + 1
    problems = manifests.validate(manifest, registry=REGISTRY)
    assert any("frames declared" in problem for problem in problems), problems
